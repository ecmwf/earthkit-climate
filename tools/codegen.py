def clean_xclim_refs(text: str) -> str:
    """
    Replace xclim-internal RST cross-references with external hyperlinks or plain text.

    Parameters
    ----------
    text : str
        Raw docstring text potentially containing xclim RST cross-references.

    Returns
    -------
    str
        Text with all recognised cross-reference roles replaced.
    """

    def _replace_roles(match: re.Match[str]) -> str:
        role = match.group(1)
        label = match.group(2)
        if role.startswith("cite:"):
            return f":cite:`{label}`"
        if role == "ref" and label in _XCLIM_REF_URL_MAP:
            display, url = _XCLIM_REF_URL_MAP[label]
            return f"`{display} <{url}>`_"
        return f"``{label}``"

    return re.sub(r":([a-z:]+):`([^`]+)`", _replace_roles, text)


def simplify_type(type_obj: Any, is_docstring: bool = False) -> str:
    """
    Simplify complex types to strings suitable for generated code or docstrings.

    Parameters
    ----------
    type_obj : Any
        The type object to simplify.
    is_docstring : bool, default=False
        If True, format type for docstrings (e.g. 'xarray.DataArray').

    Returns
    -------
    str
        The simplified type representation.
    """
    if type_obj == inspect.Parameter.empty:
        type_str = "dict[str, Any] | None"
    elif isinstance(type_obj, type):
        type_str = f"{type_obj.__module__}.{type_obj.__qualname__}"
    else:
        type_str = str(type_obj)

    da = "xarray.DataArray" if is_docstring else "xr.DataArray"
    fl = "earthkit.data.FieldList" if is_docstring else "FieldList"
    ds = "xarray.Dataset" if is_docstring else "xr.Dataset"

    replacements = {
        "<class 'xarray.core.dataarray.DataArray'>": f"{da} | {fl}",
        "<class 'xarray.core.dataset.Dataset'>": f"{ds} | {fl}",
        "xarray.core.dataarray.DataArray": f"{da} | {fl}",
        "xarray.core.dataset.Dataset": f"{ds} | {fl}",
        "xarray.core.datatree.DataTree": (f"xr.DataTree | {fl}" if not is_docstring else f"xarray.DataTree | {fl}"),
        "Quantified": f"str | float | int | {da} | {fl}",
        "DayOfYearStr": "str",
        "DateStr": "str",
        "rv_continuous": "Any",
        "Indexer": "dict[str, Any]",
    }

    for old, new in replacements.items():
        type_str = type_str.replace(old, new)

    type_str = type_str.strip("'")

    if is_docstring:
        type_str = type_str.replace("xr.", "xarray.")

    return type_str


def generate_xclim_docstring(indicator: Any, module_name: str, xclim_func_name: str) -> str:
    """
    Generate a docstring for the wrapper function based on the xclim indicator.

    Parameters
    ----------
    indicator : Any
        The xclim indicator object.
    module_name : str
        The xclim module name (e.g. 'atmos', 'land', 'seaIce').
    xclim_func_name : str
        The function name in xclim.indicators.<module_name>.

    Returns
    -------
    str
        The generated docstring for the wrapper function.
    """
    identifier = indicator.identifier.capitalize()

    summary = getattr(indicator, "title", "").strip().capitalize()
    if not summary:
        summary = (indicator.__doc__ or "").split("\n")[0].strip()

    if not summary:
        summary = f"Compute {identifier}."

    if not summary.endswith("."):
        summary += "."

    description = getattr(indicator, "abstract", "") or getattr(indicator, "description", "")
    units = getattr(indicator, "units", "")
    outputs = getattr(indicator, "var_name", None)

    sections = [summary]

    if description:
        description = clean_xclim_refs(description)
        sections.append(textwrap.fill(description, width=88))

    units_list = []
    if isinstance(units, str):
        units = units.strip()
        units_list = [units] if units else ["dimensionless"]
    elif isinstance(units, (list, tuple)):
        units_list = [u.strip() if u else "dimensionless" for u in units]
    else:
        units_list = ["dimensionless"]

    outputs_list = []
    if isinstance(outputs, str):
        outputs_list = [outputs.strip()]
    elif isinstance(outputs, (list, tuple)):
        outputs_list = [o.strip() for o in outputs]

    lines = ["**Units:**", ""]
    for out, unit in zip(outputs_list, units_list):
        lines.append(f"- {out}: {unit}")
    units_section = "\n".join(lines)

    if units_section:
        sections.append(units_section)

    link_text = f"xclim.indicators.{module_name}.{xclim_func_name}"
    link_url = f"https://xclim.readthedocs.io/en/stable/api_indicators.html#{link_text}"
    sections.append(f"This function wraps `{link_text} <{link_url}>`_.")

    params_lines = [
        "Parameters",
        "----------",
    ]

    return_doc_type = "xarray.DataArray | FieldList"
    try:
        sig = inspect.signature(indicator)
        return_doc_type = simplify_type(sig.return_annotation, is_docstring=True)
        if return_doc_type in ("dict[str, Any] | None", "Any"):
            return_doc_type = "xarray.DataArray | xarray.Dataset | FieldList | tuple[xarray.DataArray | FieldList, ...]"
        if len(return_doc_type) > 80 and return_doc_type.startswith("tuple[") and return_doc_type.endswith("]"):
            elements = return_doc_type[6:-1].split(", ")
            return_doc_type = "\n            The computed indicator.\n        ".join(elements)

        for name, param in sig.parameters.items():
            if name == "ds":
                continue
            if param.kind in (inspect.Parameter.VAR_KEYWORD, inspect.Parameter.VAR_POSITIONAL):
                continue

            param_meta = indicator.parameters.get(name)
            param_desc = getattr(param_meta, "description", "") if param_meta else ""
            type_hint = simplify_type(param.annotation, is_docstring=True)

            params_lines.append(f"{name} : {type_hint}")
            if param_desc:
                param_desc = clean_xclim_refs(param_desc)
                wrapped_description = textwrap.fill(
                    param_desc,
                    width=88,
                    initial_indent="    ",
                    subsequent_indent="    ",
                )
                params_lines.append(wrapped_description)
    except Exception:
        pass

    params_lines.append("ds : xarray.Dataset | None")
    params_lines.append("    Input dataset.")
    params_lines.append("**kwargs : Any")
    params_lines.append("    Additional keyword arguments.")

    sections.append("\n".join(params_lines))

    returns_section = inspect.cleandoc(
        f"""
        Returns
        -------
        {return_doc_type}
            The computed indicator.
    """
    )
    sections.append(returns_section)

    return "\n\n".join(sections)


def format_xclim_signature_params(indicator: Any) -> str:
    """
    Format parameters for the xclim wrapper function signature.

    Parameters
    ----------
    indicator : Any
        The xclim indicator object.

    Returns
    -------
    str
        Formatted signature parameters.
    """
    params: list[str] = []

    try:
        sig = inspect.signature(indicator)
        sig_params = list(sig.parameters.values())

        pos_no_default = []
        pos_with_default = []
        kw_only = []

        for p in sig_params:
            if p.name == "ds":
                continue
            if p.kind in (inspect.Parameter.POSITIONAL_OR_KEYWORD, inspect.Parameter.POSITIONAL_ONLY):
                if p.default == inspect.Parameter.empty:
                    pos_no_default.append(p)
                else:
                    pos_with_default.append(p)
            elif p.kind == inspect.Parameter.KEYWORD_ONLY:
                kw_only.append(p)

        for p in pos_no_default:
            type_hint = simplify_type(p.annotation)
            params.append(f"    {p.name}: {type_hint},")

        for p in pos_with_default:
            type_hint = simplify_type(p.annotation)
            default_val = repr(p.default)
            if isinstance(p.default, str) and "'" in default_val and '"' not in default_val:
                default_val = f'"{p.default}"'
            params.append(f"    {p.name}: {type_hint} = {default_val},")

        params.append("    ds: xr.Dataset | None = None,")

        if kw_only:
            params.append("    *,")
            for p in kw_only:
                type_hint = simplify_type(p.annotation)
                if p.default != inspect.Parameter.empty:
                    default_val = repr(p.default)
                    if isinstance(p.default, str) and "'" in default_val and '"' not in default_val:
                        default_val = f'"{p.default}"'
                    params.append(f"    {p.name}: {type_hint} = {default_val},")
                else:
                    params.append(f"    {p.name}: {type_hint},")
    except Exception:
        pass

    params.append("    **kwargs: Any,")
    return "\n".join(params)


def format_xclim_call_params(indicator: Any) -> str:
    """
    Format parameters forwarded to the underlying xclim indicator call.

    Parameters
    ----------
    indicator : Any
        The xclim indicator object.

    Returns
    -------
    str
        Formatted call arguments.
    """
    try:
        sig = inspect.signature(indicator)
        call_args: list[str] = []
        for name, param in sig.parameters.items():
            if name == "ds":
                call_args.append("ds=ds")
            elif param.kind in (inspect.Parameter.VAR_KEYWORD, inspect.Parameter.VAR_POSITIONAL):
                continue
            else:
                call_args.append(f"{name}={name}")
        call_args.append("**kwargs")

        total_len = sum(len(arg) for arg in call_args) + 2 * len(call_args) + 30
        if len(call_args) > 3 or total_len > 80:
            return "\n        " + ",\n        ".join(call_args) + ",\n    "

        return ", ".join(call_args)
    except Exception:
        return "ds=ds, **kwargs"


def generate_xclim_module_content(module_name: str, indicators: list[Any]) -> str:
    """
    Generate the Python source for an xclim indicator module.

    Parameters
    ----------
    module_name : str
        The xclim module name ('atmos', 'land', 'seaIce').
    indicators : list[Any]
        List of xclim indicator objects.

    Returns
    -------
    str
        The complete module source code.
    """
    functions_code: list[str] = []
    indicators.sort(key=lambda x: x.identifier)

    xclim_module = getattr(xclim.indicators, module_name)

    for ind in indicators:
        xclim_func_name = None
        for name, obj in inspect.getmembers(xclim_module):
            if obj is ind:
                xclim_func_name = name
                break

        if not xclim_func_name:
            xclim_func_name = ind.identifier

        if module_name == "atmos" and xclim_func_name in OVERLAPPING_PERCENTILES:
            func_name = f"_{xclim_func_name}"
            alias_code = f"\n\nxclim_{xclim_func_name} = _{xclim_func_name}\n"
        else:
            func_name = xclim_func_name
            alias_code = ""

        docstring = generate_xclim_docstring(ind, module_name, xclim_func_name)
        lines = docstring.split("\n")
        indented_doc = lines[0] + "\n" + "\n".join([("    " + line if line.strip() else "") for line in lines[1:]])

        signature_params = format_xclim_signature_params(ind)
        call_params = format_xclim_call_params(ind)
        xclim_obj_ref = f"xclim.indicators.{module_name}.{xclim_func_name}"

        return_type = "xr.DataArray | FieldList"
        try:
            sig = inspect.signature(ind)
            return_type = simplify_type(sig.return_annotation)
            if return_type in ("dict[str, Any] | None", "Any"):
                return_type = "xr.DataArray | xr.Dataset | FieldList | tuple[xr.DataArray | FieldList, ...]"
            if len(return_type) > 80 and return_type.startswith("tuple[") and return_type.endswith("]"):
                elements = return_type[6:-1].split(", ")
                return_type = "tuple[\n    " + ",\n    ".join(elements) + ",\n]"
        except Exception:
            pass

        code = XCLIM_FUNCTION_TEMPLATE.format(
            func_name=func_name,
            signature_params=signature_params,
            call_params=call_params,
            xclim_obj_ref=xclim_obj_ref,
            docstring=indented_doc,
            return_type=return_type,
        )
        if alias_code:
            code = code + alias_code
        functions_code.append(code)

    typing_imports = "Any, Literal" if any("Literal[" in f for f in functions_code) else "Any"

    return (
        XCLIM_MODULE_TEMPLATE.format(
            typing_imports=typing_imports,
            module_name=module_name,
            xclim_version=xclim.__version__,
            functions_code="\n".join(functions_code),
        ).rstrip()
        + "\n"
    )


def _collect_xclim_indicators(module_name: str) -> list[Any]:
    """
    Collect indicator objects from an xclim submodule.

    Parameters
    ----------
    module_name : str
        Submodule name (e.g. 'atmos', 'land', 'seaIce').

    Returns
    -------
    list[Any]
        List of indicator instances.
    """
    try:
        module = importlib.import_module(f"xclim.indicators.{module_name}")
    except ImportError:
        print(f"Skipping xclim.indicators.{module_name} (not found)")
        return []

    names = module.__all__ if hasattr(module, "__all__") else [n for n, _ in inspect.getmembers(module)]
    indicators: list[Any] = []
    for name in names:
        try:
            obj = getattr(module, name)
        except AttributeError:
            continue
        if hasattr(obj, "identifier"):
            indicators.append(obj)
    return indicators


def generate_xclim_wrappers(output_dir: pathlib.Path) -> None:
    """
    Generate all xclim indicator wrapper files.

    Parameters
    ----------
    output_dir : pathlib.Path
        Target directory where wrapper modules are written.

    Returns
    -------
    None
    """
    output_dir.mkdir(exist_ok=True, parents=True)
    for module_name in ["atmos", "land", "seaIce"]:
        output_file = output_dir / f"_xclim_{module_name.lower()}.py"
        indicators = _collect_xclim_indicators(module_name)
        print(f"Generating {output_file.name} with {len(indicators)} indicators...")
        content = generate_xclim_module_content(module_name, indicators)
        with open(output_file, "w") as f:
            f.write(content)
        print(f"Written {output_file}")


