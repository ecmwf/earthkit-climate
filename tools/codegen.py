ICCLIM_HEADER = """# SPDX-FileCopyrightText: 2026 European Centre for Medium-Range Weather Forecasts (ECMWF)
# SPDX-License-Identifier: Apache-2.0

# This file is automatically generated. Do not edit by hand.
# Generated with icclim.

from collections.abc import Callable
from typing import Any

import icclim.ecad as _icclim_ecad
import xarray as xr
from earthkit.data import FieldList

from earthkit.climate.utils.decorators import wrap_indicator


def _run_icclim_ecad(
    func: Callable[..., Any],
    short_name: str,
    data_inputs: dict[str, Any],
    ds: xr.Dataset | None,
    freq: str,
    kwargs: dict[str, Any],
) -> xr.DataArray:
    \"\"\"
    Execute an icclim ECAD indicator calculation with earthkit format handling.

    Parameters
    ----------
    func : Callable[..., Any]
        Underlying icclim function.
    short_name : str
        Short name of the ECAD index (e.g. 'SU', 'FD').
    data_inputs : dict[str, Any]
        Dictionary of input variable names and their data objects.
    ds : xarray.Dataset | None
        Input dataset containing all required variables.
    freq : str
        Resampling frequency / slice_mode.
    kwargs : dict[str, Any]
        Additional keyword arguments forwarded to the icclim function.

    Returns
    -------
    xarray.DataArray
        Calculated climate indicator.
    \"\"\"
    slice_mode = kwargs.pop("slice_mode", freq)
    logs_verbosity = kwargs.pop("logs_verbosity", "SILENT")

    in_files: Any
    if ds is not None:
        in_files = ds
    else:
        arrays = {k: v for k, v in data_inputs.items() if isinstance(v, xr.DataArray)}
        if len(arrays) == 1:
            in_files = next(iter(arrays.values()))
        elif len(arrays) > 1:
            in_files = xr.merge(list(arrays.values()))
        else:
            in_files = next(iter(data_inputs.values()))

    result = func(in_files=in_files, slice_mode=slice_mode, logs_verbosity=logs_verbosity, **kwargs)
    return result[short_name]
"""


def generate_icclim_function(item: Any) -> str:
    """
    Generate wrapper function code for an icclim ECAD index.

    Parameters
    ----------
    item : Any
        EcadIndexRegistry item.

    Returns
    -------
    str
        Generated Python function definition code.
    """
    fn_name = item.short_name.lower()
    short_name = item.short_name
    vars_list = [v.aliases[0] for v in item.input_variables] if item.input_variables else ["in_files"]

    fn = getattr(icclim.ecad, fn_name)
    sig = inspect.signature(fn)

    sig_lines: list[str] = []
    for var in vars_list:
        sig_lines.append(f'    {var}: xr.DataArray | FieldList | str = "{var}",')
    sig_lines.append("    ds: xr.Dataset | None = None,")
    sig_lines.append("    *,")
    sig_lines.append('    freq: str = "YS",')

    if "base_period_time_range" in sig.parameters:
        sig_lines.append("    base_period_time_range: list[str] | tuple[str, str] | None = None,")

    sig_lines.append("    **kwargs: Any,")
    signature_str = "\n".join(sig_lines)

    data_inputs_str = ", ".join(f'"{var}": {var}' for var in vars_list)

    param_docs: list[str] = []
    for var in vars_list:
        param_docs.append(f"    {var} : xarray.DataArray | earthkit.data.FieldList | str\n        Input {var} data.")
    param_docs.append("    ds : xarray.Dataset | None\n        Input dataset containing required variables.")
    param_docs.append("    freq : str, default='YS'\n        Resampling frequency / slice_mode.")
    if "base_period_time_range" in sig.parameters:
        param_docs.append(
            "    base_period_time_range : list[str] | tuple[str, str] | None\n"
            "        Base reference period for percentile calculations (e.g. ['1961-01-01', '1990-12-31'])."
        )
    param_docs.append("    **kwargs : Any\n        Additional keyword arguments forwarded to icclim.")
    param_docs_str = "\n".join(param_docs)

    definition_clean = (item.definition or "").strip()
    if not definition_clean.endswith("."):
        definition_clean += "."

    wrapped_definition = textwrap.fill(
        definition_clean,
        width=110,
        initial_indent="    ",
        subsequent_indent="    ",
    ).lstrip()

    if fn_name in OVERLAPPING_PERCENTILES:
        func_symbol = f"_{fn_name}"
        alias_code = f"\n\nicclim_{fn_name} = _{fn_name}\n"
    else:
        func_symbol = fn_name
        alias_code = ""

    code = f"""
@wrap_indicator()
def {func_symbol}(
{signature_str}
) -> xr.DataArray | FieldList:
    \"\"\"
    {wrapped_definition}

    Calculates the {short_name} index using the official ECA&D methodology from icclim.

    Parameters
    ----------
{param_docs_str}

    Returns
    -------
    xarray.DataArray | earthkit.data.FieldList
        Computed {short_name} climate indicator.
    \"\"\"
    extra_args: dict[str, Any] = dict(kwargs)
"""
    if "base_period_time_range" in sig.parameters:
        code += """    if base_period_time_range is not None:
        extra_args["base_period_time_range"] = base_period_time_range
"""

    code += f"""    return _run_icclim_ecad(
        _icclim_ecad.{fn_name},
        "{short_name}",
        {{{data_inputs_str}}},
        ds,
        freq,
        extra_args,
    )
"""
    if alias_code:
        code = code + alias_code
    return code


def generate_icclim_wrappers(output_dir: pathlib.Path) -> None:
    """
    Generate all icclim indicator wrapper files.

    Parameters
    ----------
    output_dir : pathlib.Path
        Target directory where wrapper modules are written.

    Returns
    -------
    None
    """
    output_dir.mkdir(exist_ok=True, parents=True)
    output_file = output_dir / "_icclim.py"

    content_parts = [ICCLIM_HEADER]
    for item in sorted(EcadIndexRegistry.values(), key=lambda x: x.short_name.lower()):
        content_parts.append(generate_icclim_function(item))

    with open(output_file, "w") as f:
        f.write("\n".join(content_parts).strip() + "\n")

    print(f"Generated {output_file} with {len(EcadIndexRegistry.values())} icclim indices.")


