def main() -> None:
    """
    Parse arguments and run selected code generation routines.

    Returns
    -------
    None
    """
    parser = argparse.ArgumentParser(
        description="Earthkit-climate indicator code generator (xclim and icclim wrappers)."
    )
    parser.add_argument(
        "--all",
        action="store_true",
        help="Generate all wrappers (both xclim and icclim). Default if none specified.",
    )
    parser.add_argument(
        "--xclim",
        action="store_true",
        help="Generate xclim indicator wrappers (_xclim_atmos.py, _xclim_land.py, _xclim_seaice.py).",
    )
    parser.add_argument(
        "--icclim",
        action="store_true",
        help="Generate icclim ECAD indicator wrappers (_icclim.py).",
    )
    args = parser.parse_args()

    run_all = args.all or (not args.xclim and not args.icclim)

    output_dir = pathlib.Path(__file__).parent.parent / "src" / "earthkit" / "climate" / "indicators" / "xarray"

    if run_all or args.xclim:
        generate_xclim_wrappers(output_dir)

    if run_all or args.icclim:
        generate_icclim_wrappers(output_dir)


if __name__ == "__main__":
    main()
